/**
 * Register a new account with email + password.
 * Firebase creates the account and generates the UID automatically.
 * @returns {Promise<{ok:boolean, user?:object, error?:string}>}
 */
export async function registerWithEmail({ name, email, password, remember = true, role }) {
  const blocked = configGuard();
  if (blocked) return blocked;
  try {
    await applyPersistence(remember);
    const cred = await createEmailUser(email.trim(), password);
    if (name) {
      try { await setDisplayName(cred.user, name.trim()); } catch (e) { console.debug('[auth] setDisplayName failed', e); }
    }
    if (role) setPendingRole(role);
    const sync = await syncProfile(true);
    return { ok: true, user: toIdentity(cred.user), profile: sync.profile || null };
  } catch (error) {
    return { ok: false, error: friendlyError(error) };
  }
}

/**
 * Sign in with email + password.
 * @returns {Promise<{ok:boolean, user?:object, profile?:object, error?:string}>}
 */
export async function loginWithEmail({ email, password, remember = false, role }) {
  const blocked = configGuard();
  if (blocked) return blocked;
  try {
    await applyPersistence(remember);
    const cred = await signInEmailUser(email.trim(), password);
    if (role) setPendingRole(role);
    const sync = await syncProfile(true);
    return { ok: true, user: toIdentity(cred.user), profile: sync.profile || null };
  } catch (error) {
    return { ok: false, error: friendlyError(error) };
  }
}

/**
 * Sign in / sign up with Google (popup). New Google users are created in
 * Firebase automatically; existing users simply sign in.
 * @returns {Promise<{ok:boolean, user?:object, error?:string}>}
 */
export async function loginWithGoogle({ remember = true, role } = {}) {
  const blocked = configGuard();
  if (blocked) return blocked;
  try {
    await applyPersistence(remember);
    const cred = await signInGoogle();
    if (role) setPendingRole(role);
    const sync = await syncProfile(true);
    return { ok: true, user: toIdentity(cred.user), profile: sync.profile || null };
  } catch (error) {
    return { ok: false, error: friendlyError(error) };
  }
}

/** Send a password reset email. */
export async function sendPasswordReset(email) {
  const blocked = configGuard();
  if (blocked) return blocked;
  try {
    await resetPassword(email.trim());
    return { ok: true };
  } catch (error) {
    return { ok: false, error: friendlyError(error) };
  }
}

/** Sign out of Firebase and clear the unverified role hint. */
export async function logout() {
  try {
    await signOutUser();
  } catch (e) {
    console.debug('[auth] signOut error', e);
  } finally {
    clearPendingRole();
    clearSessionProfile();
  }
}

/**
 * Current authenticated user as an identity object, or null.
 * Note: right after page load Firebase may not have restored the session yet;
 * prefer listenToAuthState() for reliable gating.
 */
export function getCurrentUser() {
  return toIdentity(auth.currentUser);
}

/**
 * Subscribe to Firebase auth state. Fires once with the restored user (or null)
 * and again on every login/logout. Firebase is the source of truth.
 * @param {(identity:object|null)=>void} callback
 * @returns {Function} unsubscribe
 */
export function listenToAuthState(callback) {
  return watchAuthState((user) => callback(toIdentity(user)));
}

